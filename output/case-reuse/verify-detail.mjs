import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
process.loadEnvFile('.env');
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
try {
  const origin = 'http://localhost:4111';
  const login = await context.request.post(`${origin}/auth/password/login`, { headers: {origin}, data: { email: process.env.E2E_LOGIN_EMAIL, password: process.env.E2E_LOGIN_PASSWORD, redirectUri:'/admin' } });
  expect(login.ok()).toBeTruthy();
  const session = await (await context.request.get(`${origin}/admin/api/session`)).json();
  expect(session.tenantId).toBe(process.env.E2E_TEST_TENANT_ID);
  const page = await context.newPage();
  await page.goto(`${origin}/admin/apps/qasey/cases`);
  const row = page.getByRole('row', { name: /^打开 QASEY-7：/ });
  await row.getByRole('cell').nth(1).click();
  const dialog = page.locator('dialog.case-detail-dialog');
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', {name: /v2 当前版本/})).toBeVisible();
  const step = dialog.getByRole('button',{name:'验收步骤 2：点击“收起侧边栏”。',exact:true});
  await expect(step).toBeEnabled();
  const video = dialog.locator('video');
  await video.evaluate(video => new Promise(resolve => { if(video.readyState >= 1) resolve(); else video.addEventListener('loadedmetadata',resolve,{once:true}); }));
  const caseDetail=await (await context.request.get(`${origin}/v1/case-hub/cases/QASEY-7`)).json();
  const resultId=caseDetail.current.automation.resultId;
  const timeline = await (await context.request.get(`${origin}/v1/case-hub/results/${resultId}/evidence-timeline`)).json();
  const expectedTime = timeline.steps.find(step => step.index===1).videoStartMs/1000;
  const seeked = video.evaluate(video => new Promise(resolve => video.addEventListener('seeked',()=>{video.pause();resolve(video.currentTime)},{once:true})));
  await step.click();
  const actualTime=await seeked;
  expect(actualTime).toBeGreaterThanOrEqual(expectedTime-0.01);
  expect(actualTime).toBeLessThan(expectedTime+0.2);
  await dialog.getByRole('button',{name:'调试 Trace',exact:true}).click();
  await expect(dialog.getByText('Trace 已定位 Step 02',{exact:true})).toBeVisible({timeout:30000});
  const trace = dialog.frameLocator('iframe');
  await expect(trace.locator('[role="treeitem"][aria-selected="true"] > .tree-view-entry')).toContainText('Step 02');
  await dialog.getByRole('button',{name:'验收步骤 4：点击“展开侧边栏”。',exact:true}).click();
  await expect(trace.locator('[role="treeitem"][aria-selected="true"] > .tree-view-entry')).toContainText('Step 04');
  await dialog.getByRole('button',{name:'放大 Trace',exact:true}).click();
  await expect(page.locator('dialog.evidence-lightbox')).toBeVisible();
  await expect(page.locator('dialog.evidence-lightbox').getByRole('button',{name:'验收步骤 4：点击“展开侧边栏”。',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('dialog.evidence-lightbox')).toBeHidden();
  await expect(dialog).toBeVisible();
  await page.setViewportSize({width:1280,height:720});
  await dialog.getByRole('button',{name:'播放视频',exact:true}).click();
  await dialog.getByRole('button',{name:'放大视频',exact:true}).click();
  const lightbox=page.locator('dialog.evidence-lightbox');
  const expandedVideo=lightbox.locator('video');
  await expect(expandedVideo).toBeVisible();
  const geometry=await expandedVideo.evaluate(el=>{const r=el.getBoundingClientRect();const stage=el.parentElement.getBoundingClientRect();return {top:r.top,bottom:r.bottom,height:r.height,stageBottom:stage.bottom,controls:el.controls};});
  expect(geometry.controls).toBe(true);
  expect(geometry.top).toBeGreaterThanOrEqual(0);
  expect(geometry.bottom).toBeLessThanOrEqual(720);
  expect(geometry.bottom).toBeLessThanOrEqual(geometry.stageBottom+1);
  await lightbox.getByRole('button',{name:'验收步骤 2：点击“收起侧边栏”。',exact:true}).click();
  await expandedVideo.evaluate(video => new Promise(resolve => { if(!video.seeking){video.pause();resolve();}else video.addEventListener('seeked',()=>{video.pause();resolve();},{once:true}); }));
  await page.screenshot({path:'output/case-reuse/fullscreen-video.png'});
  await page.keyboard.press('Escape');
  await expect(dialog).toBeVisible();
  const box=await dialog.boundingBox();
  await page.mouse.click(Math.max(1,box.x/2),Math.max(1,box.y/2));
  await expect(dialog).toBeHidden();
  await expect(page).toHaveURL(/\/cases$/);
  await page.getByRole('button',{name:'进入待我审阅',exact:true}).click();
  await expect(page.getByRole('heading',{name:'待我审阅',exact:true})).toBeVisible();
  await page.screenshot({path:'output/case-reuse/review-inbox.png',fullPage:true});
  await writeFile('output/case-reuse/detail-validation.json',JSON.stringify({passed:true,caseId:'QASEY-7',version:2,resultId,expectedTime,actualTime,traceSteps:[2,4],checks:['row click','current version','video seek','Trace actual selected action','fullscreen steps','Escape','backdrop','review inbox']},null,2));
  console.log(JSON.stringify({passed:true,expectedTime,actualTime,traceSteps:[2,4]}));
} finally {await context.close();await browser.close();}
